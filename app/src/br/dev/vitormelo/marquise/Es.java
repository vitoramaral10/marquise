    private static final Map<String, String> MAP = new HashMap<>();

    static {
        for (String[] pair : PAIRS) MAP.put(pair[0], pair[1]);
    }

    /** The Spanish for an English text, or the English itself when there is none. */
    static String of(String english) {
        String spanish = MAP.get(english);
        return spanish != null ? spanish : english;
    }

    /** How many texts are translated. */
    static int size() {
        return MAP.size();
    }
