#!/usr/bin/env bash
# Builds marquise.apk without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
# Needs a JDK (17+) and the Android SDK command-line tools (build-tools 34+, platform android-34). See README.md.
set -euo pipefail
cd "$(dirname "$0")"

# --- Tools
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" /opt/homebrew/share/android-commandlinetools \
           /usr/local/share/android-commandlinetools /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || { echo "Android SDK not found. Install it and set ANDROID_HOME (see README)."; exit 1; }
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
AJ="$(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1 || true)"
[ -f "${AJ:-}" ] || { echo "Android platform not found. Run: sdkmanager \"platforms;android-34\""; exit 1; }
JAVAC="${JAVA_HOME:+$JAVA_HOME/bin/}javac"
KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$JAVAC" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }

# --- Settings: config.properties -> Config.java
if [ ! -f config.properties ]; then
  cp config.example.properties config.properties
  echo "Created config.properties: add your Jellyfin key and your city there, then build again."
fi
prop() {
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" config.properties | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | tr -d '"\\')"
  printf '%s' "${v:-$2}"
}
number() {
  local v; v="$(prop "$1" "$2")"
  [[ "$v" =~ ^-?[0-9]+(\.[0-9]+)?$ ]] || { echo "config.properties: $1 must be a number (got \"$v\")" >&2; exit 1; }
  printf '%s' "$v"
}
LAT="$(number latitude 40.7128)"
LON="$(number longitude -74.0060)"
ASSIST=false; [ "$(prop disable_assistant false)" = "true" ] && ASSIST=true
VERSION="$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' app/AndroidManifest.xml)"
JELLYFIN_URL="$(prop jellyfin_url '')"

rm -rf out && mkdir -p out/gen/br/dev/vitormelo/marquise out/classes
cat > out/gen/br/dev/vitormelo/marquise/Config.java <<EOF
package br.dev.vitormelo.marquise;

/** Generated by build.sh from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String VERSION = "$VERSION";
    static final String JELLYFIN_URL = "$JELLYFIN_URL";
    static final String JELLYFIN_KEY = "$(prop jellyfin_key '')";
    static final String JELLYFIN_USER = "$(prop jellyfin_user '')";
    static final String SHELF = "$(prop shelf jellyfin,live,youtube,netflix,prime,disney,max,spotify)";
    static final String EXTRA_DISABLE = "$(prop extra_disable '')";
    static final String LATITUDE = "$LAT";
    static final String LONGITUDE = "$LON";
    static final String CITY = "$(prop city '')";
    static final String LANGUAGE = "$(prop language auto)";
    static final String TEMPERATURE = "$(prop temperature auto)";
    static final boolean DISABLE_ASSISTANT = $ASSIST;
}
EOF

# --- Build
"$BT/aapt2" compile --dir app/res -o out/res.zip
# Fonts uncompressed: Android reads them straight from the APK.
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest app/AndroidManifest.xml --java out/gen out/res.zip \
  --min-sdk-version 31 --target-sdk-version 33 -A app/assets -0 ttf
"$JAVAC" -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" -classpath "$AJ" \
  -d out/classes $(find app/src out/gen -name '*.java')
"$BT/d8" --release --min-api 31 --lib "$AJ" --output out $(find out/classes -name '*.class')
(cd out && zip -qj base.apk classes.dex)
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- Sign. Releases (CI) pass the project's key in MARQUISE_KEYSTORE / MARQUISE_KEYSTORE_PASS; otherwise your own key,
# created once (updates need the same key, so keep marquise.keystore).
KS="${MARQUISE_KEYSTORE:-marquise.keystore}"
KS_PASS="${MARQUISE_KEYSTORE_PASS:-marquise}"
if [ ! -f "$KS" ]; then
  "$KEYTOOL" -genkeypair -keystore "$KS" -alias marquise -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass "$KS_PASS" -keypass "$KS_PASS" -dname "CN=Marquise" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks "$KS" --ks-pass "pass:$KS_PASS" --key-pass "pass:$KS_PASS" --out marquise.apk out/aligned.apk
echo "Built marquise.apk ($(du -h marquise.apk | cut -f1)). Install: adb install -r marquise.apk"
